/* ══════════════════════════════════════════════════════════════════════════
 * scripts/inject-check.js —— 「拼给别的运行时代码」的交付前自检（唯一实现）
 * ══════════════════════════════════════════════════════════════════════════
 * ▎要治的病（2026-10-09 与 2026-10-08 各一次，同一个形状）：
 *   这些检查脚本把一大段 JS 写在**模板字符串**里，注入真浏览器执行。
 *   而模板字符串内部的注释里只要出现一个反引号（最常见的写法就是用反引号包个类名），
 *   模板就被**提前截断**：源文件语法完全正确，`node --check` 全过，
 *   错的是拼出来的那个字符串——于是浏览器里炸成 ReferenceError / SyntaxError，
 *   而检查脚本一条断言都没跑，报告上只是"0 通过 / 0 失败"那一行。
 * ▎为什么不在冒烟里做全仓静态红线：
 *   试过一版小状态机扫描"模板内部的块注释里有无未转义反引号"，扫 40+ 个文件报 17 处，
 *   逐条看**全是误伤**——中文注释里用反引号包代码名是本仓库的常规写法，
 *   要区分"注释在模板内部"必须连正则字面量一起解析（一个含单引号的正则就把状态机带偏）。
 *   一条会误伤 17 处的红线，下一个人撞上就直接删掉，比不装更糟（坑 110 那条纪律）。
 *   ▸ 所以换成**精确的那把尺**：谁拼代码给别的运行时执行，谁就在交付前让同一个引擎读一遍自己。
 *     这也是本项目 2026-10-08 已经用过一次的手法（把生成出来的代码 new Function 编译一遍）。
 * ▎判据：编译不过 = 立刻退出并说清是哪一段，绝不等到浏览器里那条看不懂的报错。
 * ══════════════════════════════════════════════════════════════════════════ */
'use strict';

/**
 * @param {string} file 调用方的 __filename（报错时要说清是谁家的哪一段）
 * @param {Record<string,string>} parts 变量名 → 拼出来的代码串
 */
function assertCompiles(file, parts) {
  const bad = [];
  for (const [name, src] of Object.entries(parts)) {
    if (typeof src !== 'string') { bad.push(`${name} 不是字符串（typeof=${typeof src}）`); continue; }
    try { new Function(src); } catch (e) { bad.push(`${name}: ${e.message}`); }
  }
  if (bad.length) {
    console.error(`❌ ${file} 要注入浏览器的代码编译不过：`);
    for (const b of bad) console.error(`   · ${b}`);
    console.error('   多半是模板字符串被内部的反引号提前截断了——注释里包代码名请写「」或引号，别写反引号。');
    process.exit(1);
  }
  return true;
}

module.exports = { assertCompiles };
