/* =============================================================================
 *  sfu/ai/roomActions.js —— AI「操控会议实体」的动词表与中文命中规则
 * =============================================================================
 * ▎为什么要单独成文件（2026-10-05）：
 *   原来这三张表 + detectRoomAction 写在 sfu/server.js 里，于是"用户怎么说才算数"
 *   这件事**没有任何测试能跑到**——它藏在五千行文件的一个闭包里。
 *   结果就是用户反复反馈的那句"AI 操控实体还是实现的不行"：拿一条自然语句电池去量
 *   （35 句人话），**9 句不命中 = 26% 的缺口**。表现完全对得上体感：
 *   你说"白板收起来"，它回一句漂亮话，画布一动不动。
 *   ▸ 抽成纯函数才能穷举断言（同 rdDecideFps / Asr.mergeTranscript 那条纪律：
 *     判据不抽出来，就永远只能"跑起来看着还行"）。
 *
 * ▎这张表的**边界**（比表本身更重要，别越线）：
 *   只放"房间级共享状态"——白板、字幕、视图，这些是全房共有的东西。
 *   凡动**某个人设备/权限**的（摄像头、麦克风、屏幕共享、静音别人、录制、踢人、
 *   文件、剪贴板）一律不进。test:smoke 有一条结构断言专门钉这个。
 *   ▸ 录制为什么也不行：record-start 有角色门禁（游客不能录），而 AI 本身没有身份角色，
 *     让它替人开录等于给一条越权通路——与 C1「授权绝不豁免」同一条纪律。
 *   ▸ 批注（annot）为什么也不在：它是**每个画面格自己的**开关（tile.annotOn），
 *     不是房间级状态；广播"打开批注"到底开谁的哪一格，语义根本说不清。
 *
 * ▎规则**顺序**是语义的一部分（下面断言会钉住）：
 *   "关"必须排在"开"前面判——否则「把白板关掉」里跨词的"打开白板"会被先命中；
 *   "清空/撤销"要排在"打开"前面判——否则「把白板清空」被当成"打开白板"，
 *   AI 回一句"白板已经打开"而画布没动，正是这条功能最不该出现的失败。
 *
 * ▎写法纪律：中文没有词边界，所以动词与名词之间用 `[^。，,]{0,N}` 限长间隔
 *   而**不用** `.*`（`.*` 会让"打开摄像头，顺便看看字幕"命中"打开…字幕"）——
 *   这是坑 42/49 那条老教训。JS 正则也没有 `/x` 扩展模式，每条必须写成一行。
 */

